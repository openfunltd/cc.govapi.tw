class AboutController extends MiniEngine_Controller
{
    public function indexAction()
    {
        $this->view->cc_code = $_SERVER['CCAPI_COUNCIL_CODE'] ?? 'all';
        $this->view->council_name = CouncilHelper::getName($this->view->cc_code);
    }

    public function knowledgeAction()
    {
        header('Content-Type: text/markdown; charset=utf-8');
        echo $this->generateKnowledgeMd();
        return $this->noview();
    }

    /**
     * 給 AI Agent 讀的背景知識，重點是「避免用自己既有的知識庫誤判定義」——
     * 跟 skill.md（API 怎麼呼叫）分開，這份講的是資料本身在講什麼、容易跟
     * 什麼概念搞混。內容是固定文字，不像 skill.md 需要從 Type 定義自動產生。
     */
    protected function generateKnowledgeMd(): string
    {
        return <<<'MD'
# CCAPI 背景知識（給 AI Agent 用）

這份文件是給 AI Agent 讀的背景知識，目的是避免你用自己既有知識庫裡「議會」
「議員」「council」等詞的一般定義去理解這個 API，因為那些定義通常來自其他
國家的政治制度，跟台灣地方自治的實際運作不同。API 呼叫方式（endpoint、
參數）請見 `/skill.md`，這份只講資料本身的定義。

## 這個 API 是什麼、不是什麼

- **是**：台灣「地方制度法」規範的地方議會——直轄市議會、縣（市）議會——的
  開放資料（屆期、議員、會期、場次、委員會、逐字稿）。
- **不是**立法院（國會）：立法委員、國會的資料在另一個姊妹專案
  `ly.govapi.tw`，資料完全不重疊，欄位設計相似但不是同一份資料，也不能
  互相查詢。看到「議員」不要當成「立法委員」，看到「議會」不要當成「國會」
  「Parliament」。
- **不是**鄉鎮市民代表會：地方制度法底下還有更基層的「鄉（鎮、市）民代表
  會」（代表、主席／副主席），這個 API 目前不收錄，只到縣市層級。
- 中文的「議會」在其他情境可能泛指各種合議制機關，但在這個 API 裡專指
  下面這張表的直轄市議會／縣（市）議會，範圍是明確界定的，不是泛稱。

## 台灣地方自治的層級

| 層級 | 機關名稱 | 成員稱謂 | 主持人 | 本 API 是否收錄 |
|---|---|---|---|---|
| 直轄市 | 直轄市議會 | 議員 | 議長／副議長 | ✅ |
| 縣（市） | 縣（市）議會 | 議員 | 議長／副議長 | ✅ |
| 鄉（鎮、市） | 鄉（鎮、市）民代表會 | 代表 | 主席／副主席 | ❌ 未收錄 |

## 資料實體關係

```
議會（council） → 屆（term） → 議員（councilor）
                            └→ 會期（session） → 場次（sitting） → 逐字稿（transcript）
議會（council） → 委員會（committee）  ← 不綁屆，跨屆存續
```

## 容易跟自己既有知識搞混的地方

### 議員（councilor）
- 是地方議會選出的民選代表，**不是**立法委員（國會議員）。
- 「議長」「副議長」不是獨立的實體或角色欄位，而是議員資料裡
  `職稱` = `議長`／`副議長` 的那幾筆記錄，每屆由議員互選產生，不是外部
  派任、也不是終身職。
- 每人每屆各有一筆獨立記錄，同一人連任多屆會有多筆記錄；資料裡有
  「人物代碼」欄位可以用來比對同一人跨屆的記錄，但 API 目前沒有現成的
  「查某人所有屆期」endpoint，需要自己抓「人物代碼」相同的記錄。
- `黨籍` 欄位是政黨正式全銜（例：中國國民黨、民主進步黨），不是簡稱或
  英文縮寫。
- 不是每筆記錄都代表「該屆選舉的正式當選人」：`當選狀態` 欄位會標記
  `當選`／`遞補`（原當選人出缺後依規定遞補）／`補選當選`（因出缺另外
  辦理補選），較舊的資料這個欄位可能是空值（尚未回溯建檔，不代表一定是
  正常當選）。`選區別`／`選舉區號` 是選舉區資訊，`區域` 欄位則只是
  所屬縣市名稱，兩者不要混用。

### 屆（term）
- 每個議會的屆次是**各自獨立計算**，從該議會設立時的第 1 屆起算。不同
  議會同樣寫「第 14 屆」，對應到的西元年份完全不同，不能拿來跨議會比較
  時間點。
- 屆與屆之間不一定緊密銜接，行政區劃調整、制度變革都可能造成中斷。

### 會期（session）vs 場次（sitting）
- 「會期」是一段期間（定期會／臨時會／成立大會），例如「第14屆第7次定期
  會」，本身沒有逐日細節。
- 「場次」才是會期裡逐日的排程，通常一天拆成上午／下午兩筆。
- 這兩層都**不是**單一會議的逐字內容，真正的會議逐字稿在「逐字稿」
  （transcript）實體，一個場次對應一筆逐字稿。
- **已知的分類缺口**：部分議會有不屬於「定期會／臨時會／成立大會」三種
  分類的特殊大會——例如台北市議會的「就職典禮」（議員宣誓就職＋正副議長
  選舉，於成立大會前一天召開）、新北市議會的「程序會」（正式會期開議前
  的程序性會議）。查不到這類會議的獨立分類資料，不代表議會沒開過，是
  現有 `會期類別` 分類（定期會／臨時會／成立大會）暫時沒有涵蓋到的部分。

### 委員會（committee）
- **不綁屆**，用生效日期／廢止日期記錄存續期間，是跨屆存在的常設編制，
  不是每屆重新產生、也不會每屆換一批委員會。
- 目前**沒有**「委員會成員」資料——查不到「誰在哪個委員會」。
- 各議會委員會的設置方式差異很大：大議會（如臺北市）有多個固定業務
  委員會；小議會（如連江縣）可能沒有分組委員會，直接全體審查。

### 議案（bill）
- 跟「會期」「場次」是不同顆粒度：會期／場次是「哪天上午/下午在幹嘛」，
  議案是「當天大會/委員會實際在審的個別提案」本身（案號/提案人/案由/
  審查意見/議決）。
- **目前只涵蓋 4 個議會**（雲林縣、新北市、花蓮縣、臺南市），是持續擴充中
  的實驗性補充資料，不是全國涵蓋的正式資料，跟「逐字稿」目前的定位相同。
- **`屆` 是從來源檔名解析出來的推測值，不是正式關聯欄位**，且**完全沒有
  會期代碼／場次代碼**可以連結——來源的議事錄檔案常常一份就橫跨一個定期會
  加好幾個臨時會，沒辦法精確對應到單一會期或場次，只能知道大概是哪一屆。
- `提案單位`／`提案人` 兩者通常只有一個有值：政府提案時只有 `提案單位`
  （議員提案時這欄常是空的），議員提案時只有 `提案人`。目前資料裡**沒有
  獨立的「黨團提案」主體**，跟立法院「行政院／委員／黨團」三分不同。
- `連署人` 目前絕大多數是空的，不代表該議會沒有連署制度，只是目前解析
  出來的樣本剛好沒觸發。

### 逐字稿（transcript）
- 對應到「場次」（sitting），不是對應「會期」或「議員」。
- 目前只有部分議會、部分場次有逐字稿，且原因不只一種：有些是「這個議會
  真的還沒收錄」，有些是「這個議會的逐字稿發布在其他管道，這個資料來源
  本身就抓不到」。兩種情況目前在資料上呈現方式相同（查無逐字稿），**不要
  把「查不到逐字稿」直接解讀成「這場會議沒有記錄」或「這個議會資料品質
  差」**。

## 識別碼設計原則

- 議會代碼是**自管 slug**（3 個英文字母，例：`tpe`），不是內政部行政區
  代碼、也不是 ISO 3166-2 碼。採用自管代碼是因為內政部代碼在歷史上有
  重複使用的問題（例如省轄高雄市與後來的直轄市高雄市，內政部代碼相同），
  無法唯一識別歷史上的不同機關。
- 會期代碼格式固定為 `{議會代碼}-{屆次}-{類別縮寫}{次別}`，類別縮寫
  `r`=定期會、`e`=臨時會、`i`=成立大會（沒有次別）。這個縮寫規則橫跨
  全部議會一致，可以直接從代碼反推類別，不需要另外查表。

## 資料完整度會隨時間變動，不要依賴這份文件裡的任何具體涵蓋範圍描述

各型別、各議會目前實際的資料涵蓋範圍請即時查詢
`https://all.cc.govapi.tw/viewer/collection/completeness`（依議員／會期／
場次／逐字稿四個維度，分成完整／部分缺漏／缺三種狀態，可切換是否顯示已
廢止議會），不要憑這份文件的描述或自己的推測判斷某個議會「應該」有沒有
資料。

## 跟其他開放資料 API 的關係

- `ly.govapi.tw`：立法院（國會）open API，是本專案的姊妹專案（沿用同一套
  框架），資料模型設計相似（型別、慣例命名接近），但資料內容完全不重疊，
  兩者不能互查。
MD;
